    // the value of a cast result for the client of the protocol
    inline uint16_t castResultFor(WoW::ClientProtocol const& protocol, uint16_t result)
    {
        if (result >= Count)
            return result;

        // the 1.60 client takes the 12.x values
        switch (WoW::getComparedExpansion(protocol.expansion))
        {
            case WoW::Expansion::_Classic:
                return classic[result];
            case WoW::Expansion::_TBC:
                return tbc[result];
            case WoW::Expansion::_WotLK:
                return wotlk[result];
            case WoW::Expansion::_Cata:
                return cata[result];
            case WoW::Expansion::_Mop:
                return mop[result];
            case WoW::Expansion::_WoD:
                return wod[result];
            case WoW::Expansion::_Legion:
                return legion[result];
            case WoW::Expansion::_BfA:
                return bfa[result];
            case WoW::Expansion::_Shadowlands:
                return shadowlands[result];
            case WoW::Expansion::_Dragonflight:
                return dragonflight[result];
            case WoW::Expansion::_TheWarWithin:
                return theWarWithin[result];
            case WoW::Expansion::_Midnight:
                return midnight[result];
            default:
                return result;
        }
    }
